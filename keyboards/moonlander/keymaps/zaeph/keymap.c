bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  if (record->event.pressed) {
    switch (keycode) {
    case VRSN:
      SEND_STRING(QMK_KEYBOARD "/" QMK_KEYMAP " @ " QMK_VERSION);
      return false;

    /* case ZP_UPDIR: */
    /*   SEND_STRING("../"); */
    /*   return false; */

    case ZP_WLRS:
      tap_code16(KC_COLN);
      tap_code16(KC_EQL);
      return false;

    case ZP_LARR:
      tap_code16(ZP_LABK);
      tap_code16(KC_MINS);
      return false;

    case ZP_RARR:
      tap_code16(KC_MINS);
      tap_code16(ZP_RABK);
      return false;

    case ZP_ELLS:
      tap_code16(KC_DOT);
      tap_code16(TY_NBSP);
      tap_code16(KC_DOT);
      tap_code16(TY_NBSP);
      tap_code16(KC_DOT);
      return false;
    case FR_EXCL:
    case FR_QUES:
    case FR_SCLN:
      tap_code16(TY_THSP);
      return true;
    case FR_COLN:
      tap_code16(TY_NBSP);
      return true;

    case ZP_ENDP:
      tap_code16(TY_NBSP);
      tap_code16(TY_ENDA);
      tap_code16(TY_NBSP);
      return false;

    case SET_RGB:
      zp_rgb_set_state(0);
      return false;
    }
  }

  /* Special modifiers that enable layers with extra modifiers on thumbs */
  switch (keycode) {
  case ZP_SLCT:
  case ZP_SRCT:
    if (!record->tap.count && record->event.pressed) {
      register_code(KC_LCTL);
    } else if (record->event.pressed) {
    } else {
      unregister_code(KC_LCTL);
    }
    return true;

  case ZP_SLAL:
  case ZP_SRAL:
    if (!record->tap.count && record->event.pressed) {
      register_code(KC_LALT);
    } else if (record->event.pressed) {
    } else {
      unregister_code(KC_LALT);
    }
    return true;
  }

  return true;
}


