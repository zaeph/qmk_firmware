static uint16_t ualt_timer;
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  if (record->event.pressed) {
    switch (keycode) {
    case VRSN:
      SEND_STRING(QMK_KEYBOARD "/" QMK_KEYMAP " @ " QMK_VERSION);
      return false;

    case ZP_UPDIR:
      SEND_STRING("../");
      return false;

    case ZP_WLRS:
      SEND_STRING(":=");
      return false;

    case SET_RGB:
      rgb_matrix_sethsv_noeeprom(222, 110, 255);
      return false;
    }
  }

  /* SRCT: ’ when tapped, LCTRL when held and easy extra modifiers */
  switch (keycode) {
  case ZP_SRCT:
    if (record->event.pressed) {
      ualt_timer = timer_read();
      register_code(KC_LCTL);
      layer_on(5);
    } else {
      layer_off(5);
      unregister_code(KC_LCTL);
      if (timer_elapsed(ualt_timer) < TAPPING_TERM) {
        register_code(KC_QUOTE);
        unregister_code(KC_QUOTE);
      }
    }
    break;
  }

  /* Functional ZP_SYUD, but the layer LED turns on right away and there’s no repeat */
  /* switch (keycode) { */
  /* case ZP_SYUD: */
  /*   if (record->event.pressed) { */
  /*     ualt_timer = timer_read(); */
  /*     layer_on(1); */
  /*   } else { */
  /*     layer_off(1); */
  /*     unregister_code(KC_LALT); */
  /*     if (timer_elapsed(ualt_timer) < TAPPING_TERM) { */
  /*       register_code(KC_LSFT); */
  /*       register_code(KC_MINS); */
  /*       unregister_code(KC_MINS); */
  /*       unregister_code(KC_LSFT); */
  /*     } */
  /*   } */
  /*   break; */
  /* } */

  /* Functional code to get LALT/UNDS behaviour with no repetitions */
  /* switch (keycode) { */
  /* case ZP_UALT: */
  /*   if (record->event.pressed) { */
  /*     ualt_timer = timer_read(); */
  /*     register_code(KC_LALT); */
  /*   } else { */
  /*     unregister_code(KC_LALT); */
  /*     if (timer_elapsed(ualt_timer) < TAPPING_TERM) { */
  /*       register_code(KC_LSFT); */
  /*       register_code(KC_MINS); */
  /*       unregister_code(KC_MINS); */
  /*       unregister_code(KC_LSFT); */
  /*     } */
  /*   } */
  /*   break; */
  /* } */

  return true;
}
